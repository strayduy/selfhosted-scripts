#!/usr/bin/env bash

# Vaultwarden Setup Script (Podman + Tailscale edition)
#
# Sets up a Vaultwarden instance (self-hosted Bitwarden-compatible password
# manager) running in a Podman container, with TLS provided directly by
# Tailscale. No nginx or Let's Encrypt required — the droplet must already
# be joined to a Tailscale network with MagicDNS and HTTPS certificates
# enabled in the Tailscale admin console.
#
# What this script does:
#   1. Installs Podman and dependencies
#   2. Creates a persistent data directory at /srv/vaultwarden
#   3. Fetches a TLS certificate for the Tailscale hostname
#   4. Installs a daily cert-refresh cron job
#   5. Writes an env config file at /etc/vaultwarden/vaultwarden.conf
#   6. Writes a Podman Quadlet (.container) unit for the vaultwarden user
#   7. Pulls the Vaultwarden image
#   8. Activates the Quadlet unit via systemctl --user (a transient
#      vaultwarden.service is generated by the quadlet generator)
#
# Prerequisites:
#   - Tailscale is installed, running, and the machine is joined to your tailnet
#   - MagicDNS is enabled in the Tailscale admin console (DNS → Enable MagicDNS)
#   - HTTPS certificates are enabled in the Tailscale admin console (DNS → Enable HTTPS)
#   - UFW (or equivalent) is already configured
#   - A 'vaultwarden' rootless-Podman service account already exists. Create it by
#     running, from this repo:  sudo ./server/setup_rootless_podman.sh vaultwarden
#
# Usage:
#   sudo ./setup_vaultwarden.sh <tailscale-hostname> [options]
#
#   <tailscale-hostname> is the full MagicDNS name of this machine, e.g.:
#     my-droplet.tail1234.ts.net
#
# Options:
#   --port        Port to bind Vaultwarden on the Tailscale interface (default: 443)
#   --admin-token Token for the /admin interface (default: randomly generated)
#
# Examples:
#   sudo ./setup_vaultwarden.sh my-droplet.tail1234.ts.net
#   sudo ./setup_vaultwarden.sh my-droplet.tail1234.ts.net --port 8443
#   sudo ./setup_vaultwarden.sh update 1.35.5
#
# After setup:
#   1. Visit https://<tailscale-hostname> and create your account
#   2. Visit https://<tailscale-hostname>/admin (using your admin token) to configure
#   3. Once your account is created, disable signups and the admin interface:
#        sudo ./setup_vaultwarden.sh harden
#      or edit /etc/vaultwarden/vaultwarden.conf manually and restart:
#        sudo -u vaultwarden XDG_RUNTIME_DIR=/run/user/$(id -u vaultwarden) \
#            systemctl --user restart vaultwarden

set -Eeuo pipefail
IFS=$'\n\t'

# Source shared helpers (info/success/warn/error/section, require_root, ...).
# Two valid locations: the in-repo path (when invoked from a clone) and the
# installed path (when invoked from /usr/local/sbin/, e.g. by the cert-refresh
# cron job set up by this script's `setup` command).
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
_common_found=false
for _common_candidate in \
    "$SCRIPT_DIR/../lib/common.sh" \
    "/usr/local/lib/selfhosted-scripts/common.sh"; do
    if [[ -f "$_common_candidate" ]]; then
        # shellcheck source=../lib/common.sh
        . "$_common_candidate"
        _common_found=true
        break
    fi
done
# Fail loudly here rather than letting every later call to info/error/
# require_root die with 'command not found'. error() itself is defined in
# common.sh, so this one message has to be a plain echo.
if [[ "$_common_found" != true ]]; then
    echo "[ERROR] Could not find lib/common.sh. Looked in:" >&2
    echo "          $SCRIPT_DIR/../lib/common.sh" >&2
    echo "          /usr/local/lib/selfhosted-scripts/common.sh" >&2
    echo "        Run this script from a full clone of the repo (it needs the" >&2
    echo "        sibling lib/ directory), not as a lone copied file." >&2
    exit 1
fi
unset _common_candidate _common_found

trap 'error "Failed at line $LINENO (command: $BASH_COMMAND)"' ERR

# ── Constants ─────────────────────────────────────────────────────────────────
# Pinned by tag AND digest. The tag is for humans; Podman ignores it when a
# digest is present and pulls exactly the image (multi-arch index) below, so a
# re-pushed or compromised tag on Docker Hub can't change what runs.
# WebSockets are on the main port (v1.29+).
#
# To update the pin:
#   1. Pick a release from https://github.com/dani-garcia/vaultwarden/releases
#   2. Look up its multi-arch index digest (the sha256 of the raw manifest
#      bytes; use the index, not the per-arch amd64 manifest):
#        skopeo inspect --raw docker://docker.io/vaultwarden/server:<VER> | sha256sum
#   3. Update both the tag and the digest below.
#   4. Roll existing instances forward with `sudo ./setup_vaultwarden.sh update`.
#      Do NOT re-run `setup` to update — it rewrites the env file with a fresh
#      admin token and undoes `harden`.
VW_IMAGE="docker.io/vaultwarden/server:1.37.5@sha256:4fe17f415f90087377d37c755e0ea3cf189dcc6794e49cdd2a9adbb4937d9e1f"

# Dedicated unprivileged system user — Podman runs rootless under this account
# so a container escape cannot yield root on the host.
VW_SYSTEM_USER="vaultwarden"

VW_DATA_DIR="/srv/vaultwarden"
VW_CERT_DIR="/srv/vaultwarden/certs"
VW_CONF_DIR="/etc/vaultwarden"
VW_ENV_FILE="$VW_CONF_DIR/vaultwarden.conf"

# Quadlet (.container) file — a systemd-podman generator reads it on
# `systemctl --user daemon-reload` and synthesises a transient
# vaultwarden.service unit. See podman-systemd.unit(5). Quadlet ships with
# Podman 4.4+; Ubuntu 24.04's 4.9.3 supports it natively.
VW_QUADLET_DIR="/home/$VW_SYSTEM_USER/.config/containers/systemd"
VW_QUADLET_FILE="$VW_QUADLET_DIR/vaultwarden.container"

# Data-dir backups taken by `update` before restarting on a new image.
VW_BACKUP_DIR="/root/vaultwarden-backups"

# Health check after (re)starting the container: 12 × 5s = 60s.
VW_HEALTH_RETRIES=12
VW_HEALTH_INTERVAL=5

# Where this script and its shared helpers are installed during `setup`, so the
# cert-refresh cron job and post-setup invocations (`harden`, `cert-refresh`)
# work even if the original clone is deleted.
INSTALLED_SCRIPT="/usr/local/sbin/setup_vaultwarden.sh"
INSTALLED_COMMON="/usr/local/lib/selfhosted-scripts/common.sh"

# ── Root check ────────────────────────────────────────────────────────────────
require_root
require_ubuntu "24.04"

# ── Tailscale check ───────────────────────────────────────────────────────────
# require_rootless_podman_user and systemctl_user (used throughout this script)
# come from lib/common.sh, sourced above.

check_tailscale() {
    if ! command -v tailscale &>/dev/null; then
        error "Tailscale is not installed. Install and join your tailnet first."
    fi

    local ts_status
    ts_status=$(tailscale status --json 2>/dev/null | jq -r '.BackendState // ""' 2>/dev/null || echo "")
    if [[ "$ts_status" != "Running" ]]; then
        warn "Tailscale is not running or not authenticated (state: ${ts_status:-unknown})"
        warn "Run: tailscale up"
        exit 1
    fi
}

# ══════════════════════════════════════════════════════════════════════════════
# CERT REFRESH — fetch/renew Tailscale TLS cert and copy into the data dir
# ══════════════════════════════════════════════════════════════════════════════
cmd_cert_refresh() {
    local hostname="${1:-}"

    [[ -n "$hostname" ]] || error "hostname is required for cert-refresh"

    info "Fetching Tailscale TLS certificate for $hostname..."

    # Snapshot the fingerprint of the cert already in place (if any) so we can
    # detect whether tailscale cert actually issued a new one.
    local old_fingerprint=""
    if [[ -f "$VW_CERT_DIR/fullchain.pem" ]]; then
        old_fingerprint=$(openssl x509 -noout -fingerprint -sha256 \
            -in "$VW_CERT_DIR/fullchain.pem" 2>/dev/null || true)
    fi

    # Ensure the cert dir exists and has correct ownership/permissions whether
    # this is called from setup or standalone (e.g. cert-refresh subcommand).
    mkdir -p "$VW_CERT_DIR"
    chown root:"$VW_SYSTEM_USER" "$VW_CERT_DIR"
    chmod 750 "$VW_CERT_DIR"

    tailscale cert --cert-file "/var/lib/tailscale/certs/${hostname}.crt" \
        --key-file "/var/lib/tailscale/certs/${hostname}.key" \
        "$hostname"

    cp "/var/lib/tailscale/certs/${hostname}.crt" "$VW_CERT_DIR/fullchain.pem"
    cp "/var/lib/tailscale/certs/${hostname}.key" "$VW_CERT_DIR/privkey.pem"

    # The key must be readable by the vaultwarden user (which runs the rootless
    # container) but not world-readable. The cert is public so 644 is fine.
    chown root:"$VW_SYSTEM_USER" "$VW_CERT_DIR/privkey.pem" "$VW_CERT_DIR/fullchain.pem"
    chmod 640 "$VW_CERT_DIR/privkey.pem"
    chmod 644 "$VW_CERT_DIR/fullchain.pem"

    success "Certificate copied to $VW_CERT_DIR"

    # Only restart if the cert actually changed — avoids a needless service
    # interruption on days when tailscale cert returns the cached cert unchanged.
    local new_fingerprint
    new_fingerprint=$(openssl x509 -noout -fingerprint -sha256 \
        -in "$VW_CERT_DIR/fullchain.pem" 2>/dev/null || true)

    if [[ "$old_fingerprint" = "$new_fingerprint" && -n "$new_fingerprint" ]]; then
        info "Certificate unchanged — skipping Vaultwarden restart"
    elif systemctl_user "$VW_SYSTEM_USER" is-active --quiet vaultwarden 2>/dev/null; then
        systemctl_user "$VW_SYSTEM_USER" restart vaultwarden
        success "Vaultwarden restarted to pick up new certificate"
    fi
}

# ══════════════════════════════════════════════════════════════════════════════
# HARDEN — disable signups and admin interface post-setup
# ══════════════════════════════════════════════════════════════════════════════
cmd_harden() {
    section "Hardening Vaultwarden"

    if [[ ! -f "$VW_ENV_FILE" ]]; then
        warn "Vaultwarden config not found at $VW_ENV_FILE"
        warn "Has Vaultwarden been set up yet?"
        exit 1
    fi

    # Disable signups
    if grep -q '^SIGNUPS_ALLOWED=false' "$VW_ENV_FILE"; then
        info "SIGNUPS_ALLOWED already false — skipping"
    else
        sed -i 's/^SIGNUPS_ALLOWED=.*/SIGNUPS_ALLOWED=false/' "$VW_ENV_FILE"
        success "Signups disabled"
    fi

    # Disable admin interface
    if grep -q '^#ADMIN_TOKEN=' "$VW_ENV_FILE"; then
        info "Admin interface already disabled — skipping"
    elif grep -q '^ADMIN_TOKEN=' "$VW_ENV_FILE"; then
        sed -i 's/^ADMIN_TOKEN=/#ADMIN_TOKEN=/' "$VW_ENV_FILE"
        success "Admin interface disabled"
    else
        warn "ADMIN_TOKEN line not found in $VW_ENV_FILE — check manually"
    fi

    systemctl_user "$VW_SYSTEM_USER" restart vaultwarden
    success "Vaultwarden restarted with hardened config"
    info "To re-enable the admin interface, edit $VW_ENV_FILE,"
    info "uncomment ADMIN_TOKEN, and run:"
    info "  sudo -u $VW_SYSTEM_USER XDG_RUNTIME_DIR=/run/user/\$(id -u $VW_SYSTEM_USER) systemctl --user restart vaultwarden"
    echo ""
}

# ══════════════════════════════════════════════════════════════════════════════
# SHARED HELPERS — used by both `setup` and `update`
# ══════════════════════════════════════════════════════════════════════════════

# Poll https://<hostname>:<port>/alive until Vaultwarden answers.
# Returns 0 when healthy, 1 on timeout — callers decide how to react, so this
# must never call error().
#
# Usage: wait_for_healthy <hostname> <port> <ts_ip>
wait_for_healthy() {
    local hostname="$1" port="$2" ts_ip="$3"

    info "Waiting for Vaultwarden to be ready..."
    local i
    for ((i = 1; i <= VW_HEALTH_RETRIES; i++)); do
        # Use --resolve to map the Tailscale hostname to its IP so curl can
        # verify the TLS certificate's SAN properly — avoids --insecure.
        if curl -sf --resolve "${hostname}:${port}:${ts_ip}" \
            "https://${hostname}:${port}/alive" &>/dev/null; then
            success "Vaultwarden is responding on $hostname:$port"
            return 0
        fi
        info "  Not ready yet (attempt $i/$VW_HEALTH_RETRIES)..."
        # On the final attempt, exit the loop immediately without sleeping.
        ((i == VW_HEALTH_RETRIES)) && break
        info "  Waiting ${VW_HEALTH_INTERVAL}s before next attempt..."
        sleep "$VW_HEALTH_INTERVAL"
    done

    warn "Vaultwarden didn't respond after $((VW_HEALTH_RETRIES * VW_HEALTH_INTERVAL))s"
    return 1
}

# Echo the image reference currently pinned in the installed quadlet.
quadlet_image() {
    local line
    line=$(grep -m1 '^Image=' "$VW_QUADLET_FILE" 2>/dev/null || true)
    printf '%s' "${line#Image=}"
}

# Echo the host port from the quadlet's PublishPort=<ip>:<host>:<container>.
quadlet_port() {
    local line
    line=$(grep -m1 '^PublishPort=' "$VW_QUADLET_FILE" 2>/dev/null || true)
    line="${line#PublishPort=}"
    # <ip>:<hostport>:<containerport> — take the middle field.
    printf '%s' "$(cut -d: -f2 <<<"$line")"
}

# Split an image reference "registry/repo[:tag][@sha256:...]".
# A ':' only marks a tag if it's in the last path component (registries can
# carry a port, e.g. host:5000/repo) and before any '@digest'.
#
# Usage: image_repo <ref>   -> registry/repo
#        image_tag <ref>    -> tag (or "latest" if none)
image_repo() {
    local ref="${1%@*}"
    local last="${ref##*/}"
    [[ "$last" == *:* ]] && ref="${ref%:*}"
    printf '%s' "$ref"
}
image_tag() {
    local ref="${1%@*}"
    local last="${ref##*/}"
    if [[ "$last" == *:* ]]; then
        printf '%s' "${last##*:}"
    else
        printf 'latest'
    fi
}

# Rewrite the Image= line of the installed quadlet in place.
#
# Read-modify-write with shell parameter expansion rather than `sed -i`:
# sed -i replaces the inode, which would reset the file to root:root and break
# the quadlet generator (it only reads files owned by the user). Writing via
# `tee` as the vaultwarden user keeps ownership and permissions intact.
#
# Usage: set_quadlet_image <image-ref>
set_quadlet_image() {
    local new_image="$1"
    local content="" line
    while IFS= read -r line; do
        # Only a line *starting* with Image= is the directive; the update
        # instructions in the file's header comment must stay untouched.
        [[ "$line" == Image=* ]] && line="Image=$new_image"
        content+="$line"$'\n'
    done <"$VW_QUADLET_FILE"
    printf '%s' "$content" | run_as_user "$VW_SYSTEM_USER" tee "$VW_QUADLET_FILE" >/dev/null
    chmod 644 "$VW_QUADLET_FILE"
}

# ══════════════════════════════════════════════════════════════════════════════
# UPDATE — roll the container forward to a new image, with backup + rollback
# ══════════════════════════════════════════════════════════════════════════════
#
# Deliberately does NOT touch $VW_ENV_FILE: re-running `setup` would regenerate
# the admin token and undo `harden`. This only swaps the pinned image.
cmd_update() {
    local target="" do_backup=true

    while [[ $# -gt 0 ]]; do
        case "$1" in
            --no-backup)
                do_backup=false
                shift
                ;;
            --help | -h)
                usage
                exit 0
                ;;
            -*) error "Unknown option: $1" ;;
            *)
                [[ -n "$target" ]] && error "Unexpected extra argument: $1"
                target="$1"
                shift
                ;;
        esac
    done

    # ── Preflight ─────────────────────────────────────────────────────────────
    [[ -f "$VW_QUADLET_FILE" ]] \
        || error "No quadlet at $VW_QUADLET_FILE — has Vaultwarden been set up?"
    require_rootless_podman_user "$VW_SYSTEM_USER"

    local current_image
    current_image=$(quadlet_image)
    [[ -n "$current_image" ]] || error "No Image= line found in $VW_QUADLET_FILE"

    # Resolve the target image reference:
    #   (no arg)          -> VW_IMAGE pinned at the top of this script
    #   1.35.5            -> <current repository>:1.35.5
    #   repo/name:tag     -> used verbatim (allows switching to the alpine tag)
    # A target without a digest is pinned to the digest it resolves to right
    # after the pull (Step 1), so the installed quadlet is always tag@digest.
    local target_image
    if [[ -z "$target" ]]; then
        target_image="$VW_IMAGE"
    elif [[ "$target" == *"/"* ]]; then
        target_image="$target"
    else
        target_image="$(image_repo "$current_image"):${target}"
    fi
    [[ "$target_image" =~ ^[A-Za-z0-9._/-]+(:[A-Za-z0-9._-]+)?(@sha256:[a-f0-9]{64})?$ ]] \
        || error "Invalid image reference: $target_image"

    section "Updating Vaultwarden"
    info "Current image: $current_image"
    info "Target image:  $target_image"

    # Comparing without the digest for tag-only targets also means a re-pushed
    # tag isn't silently followed: same tag => nothing to do.
    if [[ "$current_image" == "$target_image" ||
        ("$target_image" != *@sha256:* && "${current_image%@*}" == "$target_image") ]]; then
        success "Already running $current_image — nothing to do"
        return 0
    fi

    # Health-check coordinates, resolved before we touch anything so a missing
    # tailnet aborts the update rather than a half-applied one.
    local hostname ts_ip port
    hostname=$(tailscale status --json 2>/dev/null \
        | jq -r '.Self.DNSName | rtrimstr(".")' 2>/dev/null || echo "")
    ts_ip=$(tailscale ip -4 2>/dev/null || true)
    port=$(quadlet_port)

    # ── Step 1: Pull the new image (before stopping anything) ─────────────────
    info "Step 1: Pulling $target_image..."
    run_as_user "$VW_SYSTEM_USER" podman pull "$target_image"
    success "Image pulled"

    # Pin a tag-only target to the digest just pulled, so later re-pushes of
    # the tag on the registry can't change what this instance runs.
    if [[ "$target_image" != *@sha256:* ]]; then
        local digest
        digest=$(run_as_user "$VW_SYSTEM_USER" \
            podman image inspect --format '{{.Digest}}' "$target_image" 2>/dev/null || true)
        if [[ "$digest" =~ ^sha256:[a-f0-9]{64}$ ]]; then
            target_image="${target_image}@${digest}"
            info "Pinned to digest: $target_image"
        else
            warn "Could not resolve the pulled image's digest — pinning by tag only"
        fi
    fi

    # ── Step 2: Stop the service ──────────────────────────────────────────────
    info "Step 2: Stopping Vaultwarden..."
    systemctl_user "$VW_SYSTEM_USER" stop vaultwarden.service || true
    success "Service stopped"

    # ── Step 3: Back up the data directory ────────────────────────────────────
    # Taken with the container stopped so the SQLite DB is quiescent.
    local backup_file=""
    if [[ "$do_backup" == true ]]; then
        mkdir -p "$VW_BACKUP_DIR"
        chmod 700 "$VW_BACKUP_DIR"
        backup_file="$VW_BACKUP_DIR/vaultwarden-$(date +%Y%m%d-%H%M%S)-pre-$(image_tag "$target_image").tar.gz"
        info "Step 3: Backing up $VW_DATA_DIR to $backup_file..."
        tar czf "$backup_file" -C "$(dirname "$VW_DATA_DIR")" "$(basename "$VW_DATA_DIR")"
        chmod 600 "$backup_file"
        success "Backup written ($(du -h "$backup_file" | cut -f1))"
    else
        warn "Step 3: --no-backup given — skipping data backup"
    fi

    # ── Step 4: Repin the image and restart ───────────────────────────────────
    info "Step 4: Repinning image and reloading quadlet..."
    set_quadlet_image "$target_image"
    systemctl_user "$VW_SYSTEM_USER" daemon-reload
    # `start` can legitimately fail (bad image, failed DB migration); handle it
    # ourselves so the rollback below runs instead of the ERR trap firing.
    local started=true
    systemctl_user "$VW_SYSTEM_USER" start vaultwarden.service || started=false

    # ── Step 5: Health check, rolling back on failure ─────────────────────────
    local healthy=false
    if [[ "$started" == true ]]; then
        if [[ -n "$hostname" && -n "$ts_ip" && -n "$port" ]]; then
            wait_for_healthy "$hostname" "$port" "$ts_ip" && healthy=true
        else
            warn "Could not determine hostname/IP/port — skipping HTTP health check"
            systemctl_user "$VW_SYSTEM_USER" is-active --quiet vaultwarden.service \
                && healthy=true
        fi
    fi

    if [[ "$healthy" == false ]]; then
        warn "Update to $target_image failed — rolling back to $current_image"
        set_quadlet_image "$current_image"
        systemctl_user "$VW_SYSTEM_USER" daemon-reload
        systemctl_user "$VW_SYSTEM_USER" start vaultwarden.service || true
        warn "Rolled back. Inspect the failure with:"
        warn "  sudo -u $VW_SYSTEM_USER journalctl --user-unit vaultwarden -n 100"
        [[ -n "$backup_file" ]] && warn "Data backup (restore if a migration corrupted the DB): $backup_file"
        error "Update aborted"
    fi

    section "Vaultwarden updated to $target_image"
    echo ""
    [[ -z "$backup_file" ]] || info "Pre-update backup: $backup_file"
    info "Old images are kept for rollback. Remove them once you're happy:"
    info "  cd / && sudo -u $VW_SYSTEM_USER podman image prune -f"
    info "To roll back manually:"
    info "  sudo $0 update $current_image"
    echo ""
}

# ══════════════════════════════════════════════════════════════════════════════
# SETUP
# ══════════════════════════════════════════════════════════════════════════════
cmd_setup() {
    # ── Parse arguments ───────────────────────────────────────────────────────
    local hostname="${1:-}"
    shift
    local port=443 admin_token=""

    while [[ $# -gt 0 ]]; do
        case "$1" in
            --port)
                port="$2"
                shift 2
                ;;
            --admin-token)
                admin_token="$2"
                shift 2
                ;;
            --help | -h)
                usage
                exit 0
                ;;
            *) error "Unknown option: $1" ;;
        esac
    done

    [[ -z "$hostname" ]] && error "Tailscale hostname is required"

    if ! [[ "$port" =~ ^[0-9]+$ ]] || ((port < 1 || port > 65535)); then
        error "Invalid port '$port' — must be an integer between 1 and 65535"
    fi

    # ── Install jq (required for preflight JSON parsing below) ──────────────
    # jq is needed by check_tailscale() and the hostname-verification block
    # that follow. argon2 is installed later in Step 1 once we know we are
    # ready to hash the admin token.
    info "Installing prerequisite: jq..."
    apt-get update
    DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends jq

    # ── Preflight checks ──────────────────────────────────────────────────────
    require_rootless_podman_user "$VW_SYSTEM_USER"
    check_tailscale

    # Resolve the Tailscale IP for this machine — used to bind Rocket to the
    # Tailscale interface only, so Vaultwarden is not reachable on the public IP
    local ts_ip
    ts_ip=$(tailscale ip -4 2>/dev/null || true)
    if [[ -z "$ts_ip" ]]; then
        error "Could not determine Tailscale IPv4 address. Is the machine on the tailnet?"
    fi
    info "Tailscale IPv4: $ts_ip"

    # Validate that the supplied hostname matches this machine's actual Tailscale
    # MagicDNS name. A mismatch means the cert will be for the wrong host.
    local actual_hostname
    actual_hostname=$(tailscale status --json 2>/dev/null \
        | jq -r '.Self.DNSName | rtrimstr(".")' \
            2>/dev/null || echo "")
    if [[ -z "$actual_hostname" ]]; then
        warn "Could not verify Tailscale hostname (MagicDNS may not be enabled)."
        warn "Continuing with supplied hostname: $hostname"
    elif [[ "$hostname" != "$actual_hostname" ]]; then
        warn "Supplied hostname '$hostname' does not match this machine's Tailscale hostname '$actual_hostname'."
        warn "The TLS certificate would be for the wrong host. Did you mean:"
        warn "  sudo $0 $actual_hostname"
        exit 1
    else
        info "Hostname verified: $hostname"
    fi

    # Check for existing installation before doing anything destructive
    if [[ -f "$VW_ENV_FILE" || -f "$VW_QUADLET_FILE" ]]; then
        warn "Vaultwarden appears to already be installed."
        warn "To remove it, stop and disable the service, then remove $VW_CONF_DIR and $VW_DATA_DIR."
        exit 1
    fi

    # Generate the raw admin token now (before any installs) so we can fail
    # fast on bad input. The actual Argon2 hashing happens after Step 1
    # installs the argon2 package.
    if [[ -z "$admin_token" ]]; then
        admin_token=$(openssl rand -hex 32)
    fi

    section "Setting up Vaultwarden on $hostname (port $port)"

    # ── Step 1: Install dependencies ──────────────────────────────────────────
    info "Step 1: Installing argon2..."
    # apt-get update was already run above to install jq; no need to repeat it.
    # podman-compose is no longer needed — we use Quadlet (.container files)
    # which generates a systemd unit directly, without docker-compose.
    DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends argon2
    success "Dependencies installed"

    # Hash the admin token now that argon2 is available.
    # Vaultwarden expects an Argon2id hash in ADMIN_TOKEN — storing plaintext
    # works but triggers a startup warning and exposes the token in the config.
    # The raw token goes into a root-only reveal file; never to the terminal.
    local salt
    salt=$(openssl rand -base64 16)
    local admin_token_hash
    admin_token_hash=$(echo -n "$admin_token" | argon2 "$salt" -id -t 3 -m 17 -p 4 -l 32 -e)

    # Write the raw token to a one-time reveal file, never to the terminal.
    local token_reveal_file="/root/vaultwarden-admin-token.txt"
    # We only get here if $VW_ENV_FILE doesn't exist (checked above), so a
    # leftover file is from a run that never finished and its token was never
    # activated. Move it aside rather than aborting — aborting left re-runs
    # stuck until the file was removed by hand.
    if [[ -f "$token_reveal_file" ]]; then
        local stale_file
        stale_file="$token_reveal_file.$(date +%Y%m%d_%H%M%S).old"
        mv "$token_reveal_file" "$stale_file"
        warn "Moved unused token file from an unfinished run to $stale_file."
        warn "Delete it: sudo rm $stale_file"
    fi
    cat >"$token_reveal_file" <<EOF
Vaultwarden admin token — delete this file after noting the token down.
Generated: $(date)

Raw token (paste this into the /admin login page):
$admin_token

The Argon2 hash of this token is stored in $VW_ENV_FILE.
EOF
    chmod 600 "$token_reveal_file"
    info "Admin token written to $token_reveal_file (root-only)"
    warn "Read it with: sudo cat $token_reveal_file"
    warn "Delete it after noting the token: sudo rm $token_reveal_file"

    # ── Step 2: Create system user and directories ────────────────────────────
    info "Step 2: Creating directories..."

    mkdir -p "$VW_DATA_DIR"
    mkdir -p "$VW_CERT_DIR"
    mkdir -p "$VW_CONF_DIR"
    # Data dir is owned by the system user.
    chown -R "$VW_SYSTEM_USER:$VW_SYSTEM_USER" "$VW_DATA_DIR"
    # Config dir stays root-owned (it holds the admin token hash) but the
    # vaultwarden user needs execute permission to enter it so it can read
    # the group-readable env file referenced by the Quadlet's EnvironmentFile=.
    chown root:"$VW_SYSTEM_USER" "$VW_CONF_DIR"
    chmod 750 "$VW_CONF_DIR"
    success "Directories created"

    # ── Step 3: Fetch TLS certificate ─────────────────────────────────────────
    section "Step 3: Fetching Tailscale TLS certificate"
    info "This requires HTTPS certificates to be enabled in your Tailscale admin console"
    info "(DNS → Enable HTTPS)"
    cmd_cert_refresh "$hostname"

    # ── Step 4: Install this script + cert-refresh cron job ──────────────────
    info "Step 4: Installing script and certificate refresh cron job..."

    # Install the script and its sourced helper to fixed paths so that the
    # cert-refresh cron job and the post-setup `harden` / `cert-refresh`
    # subcommands work even if the original clone directory is deleted.
    #
    # Previously this step generated a separate /usr/local/bin/vaultwarden-cert-refresh
    # wrapper that inlined the cert-refresh logic. That duplicated cmd_cert_refresh()
    # and the two implementations could drift. Now cron just calls back into
    # this script's `cert-refresh` subcommand — single source of truth.
    install -m 755 "${BASH_SOURCE[0]}" "$INSTALLED_SCRIPT"
    install -d -m 755 "$(dirname "$INSTALLED_COMMON")"
    install -m 644 "$SCRIPT_DIR/../lib/common.sh" "$INSTALLED_COMMON"
    success "Script installed at $INSTALLED_SCRIPT"

    # Run daily at 04:00 — Tailscale certs are valid for ~90 days so this is
    # ample headroom. `tailscale cert` is a no-op if the cert is still fresh,
    # and cmd_cert_refresh() skips the Vaultwarden restart if the cert
    # fingerprint is unchanged.
    cat >/etc/cron.d/vaultwarden-cert-refresh <<CRON_EOF
# Vaultwarden Tailscale cert refresh — managed by setup_vaultwarden.sh
0 4 * * * root $INSTALLED_SCRIPT cert-refresh $hostname >> /var/log/vaultwarden-cert-refresh.log 2>&1
CRON_EOF
    success "Cron job installed: daily at 04:00 (calls $INSTALLED_SCRIPT cert-refresh)"

    # ── Step 5: Write env config ──────────────────────────────────────────────
    info "Step 5: Writing Vaultwarden config to $VW_ENV_FILE..."

    cat >"$VW_ENV_FILE" <<EOF
# Vaultwarden environment configuration
# Managed by setup_vaultwarden.sh
#
# After creating your account, run: sudo ./setup_vaultwarden.sh harden
# This will set SIGNUPS_ALLOWED=false and disable the admin interface.

# Bind Rocket to all interfaces inside the container.
ROCKET_ADDRESS=0.0.0.0

# Port Vaultwarden's web server (Rocket) listens on.
ROCKET_PORT=$port

# TLS certificate and key — provided by Tailscale, refreshed daily by cron.
# These paths are inside the container (mounted from $VW_CERT_DIR on the host).
ROCKET_TLS={certs="/data/certs/fullchain.pem",key="/data/certs/privkey.pem"}

# Allow new user registrations. Set to false after creating your account
# by running: sudo ./setup_vaultwarden.sh harden
SIGNUPS_ALLOWED=true

# Require email verification on signup (requires SMTP config below)
SIGNUPS_VERIFY=false

# Prevent users from creating organisations (and thus inviting others).
# Set to a comma-separated list of email addresses to whitelist specific users,
# or leave empty ("") to allow all users to create orgs.
ORG_CREATION_USERS=none

# Admin interface token — treat this like a password.
# Stored as an Argon2id hash; paste the RAW token (from /root/vaultwarden-admin-token.txt)
# into the browser, NOT the hash. Comment out to disable the /admin interface entirely.
ADMIN_TOKEN=ADMIN_TOKEN_PLACEHOLDER

# Don't show password hints on the login page
SHOW_PASSWORD_HINT=false

# --- Optional: SMTP for email notifications and signup verification ---
# Uncomment and fill in to enable email support.
#SMTP_HOST=smtp.example.com
#SMTP_PORT=587
#SMTP_SECURITY=starttls
#SMTP_USERNAME=you@example.com
#SMTP_PASSWORD=yourpassword
#SMTP_FROM=vaultwarden@example.com
EOF

    # Protect the config — it contains the admin token hash.
    # Group-readable so the vaultwarden user (which runs podman) can read it;
    # root-owned so only root can modify it.
    chown root:"$VW_SYSTEM_USER" "$VW_ENV_FILE"
    chmod 640 "$VW_ENV_FILE"

    # Substitute the placeholder with the Argon2id hash.
    # Avoid sed: Argon2id hashes contain literal $ characters (e.g.
    # $argon2id$v=19$m=…) alongside /, &, and \ — the full set is awkward to
    # escape correctly for a sed replacement string. Shell parameter expansion
    # treats the replacement as a plain literal, so there is nothing to escape.
    # Using > instead of sed -i also preserves the chown/chmod applied above
    # (sed -i replaces the inode on Linux, resetting ownership to root:root).
    local env_content
    env_content=$(<"$VW_ENV_FILE")
    env_content="${env_content/ADMIN_TOKEN_PLACEHOLDER/$admin_token_hash}"
    printf '%s\n' "$env_content" >"$VW_ENV_FILE"

    success "Config written (permissions: root-only read)"

    # ── Step 6: Write Quadlet (.container) unit ───────────────────────────────
    # See podman-systemd.unit(5). systemd's quadlet generator reads .container
    # files on `systemctl --user daemon-reload` and synthesises a matching
    # vaultwarden.service unit at runtime.
    info "Step 6: Writing Quadlet unit to $VW_QUADLET_FILE..."

    run_as_user "$VW_SYSTEM_USER" mkdir -p "$VW_QUADLET_DIR"

    run_as_user "$VW_SYSTEM_USER" tee "$VW_QUADLET_FILE" >/dev/null <<EOF
# Vaultwarden — managed by setup_vaultwarden.sh
# Quadlet generates vaultwarden.service from this file.
#
# Manage as the vaultwarden user (linger keeps the user session alive):
#   sudo -u $VW_SYSTEM_USER XDG_RUNTIME_DIR=/run/user/\$(id -u $VW_SYSTEM_USER) \\
#       systemctl --user {start,stop,restart,status} vaultwarden
#   journalctl --user-unit vaultwarden -f
#
# Update:  do not hand-edit Image= — use the update subcommand, which backs up
#          the data dir, health-checks the new image and rolls back on failure:
#   sudo $INSTALLED_SCRIPT update 1.35.5

[Unit]
Description=Vaultwarden password manager (Podman Quadlet + Tailscale)
Documentation=https://github.com/dani-garcia/vaultwarden

[Container]
Image=$VW_IMAGE
ContainerName=vaultwarden
EnvironmentFile=$VW_ENV_FILE
# Persistent data (SQLite DB, attachments, etc.) and TLS certs.
# :Z relabels for SELinux; harmless on Ubuntu (AppArmor) but kept for portability.
Volume=$VW_DATA_DIR:/data:Z
# Bind only to the Tailscale interface — not reachable on the public IP.
PublishPort=$ts_ip:$port:$port
# Defense-in-depth resource limits in case of container escape or runaway process.
Memory=512M
PidsLimit=512

[Service]
# Restart on failure, but not on clean exits (e.g. manual stop).
Restart=on-failure
RestartSec=10

[Install]
# default.target is the rootless-user equivalent of multi-user.target.
WantedBy=default.target
EOF

    chmod 644 "$VW_QUADLET_FILE"
    success "Quadlet unit written"

    # ── Step 7: Pull image ────────────────────────────────────────────────────
    info "Step 7: Pulling Vaultwarden image ($VW_IMAGE)..."
    run_as_user "$VW_SYSTEM_USER" podman pull "$VW_IMAGE"
    success "Image pulled"

    # ── Step 8: Activate Quadlet unit ─────────────────────────────────────────
    # daemon-reload triggers the quadlet generator to read VW_QUADLET_FILE and
    # produce a transient vaultwarden.service unit in the user session.
    info "Step 8: Activating Quadlet unit..."

    systemctl_user "$VW_SYSTEM_USER" daemon-reload
    # Quadlet-generated units cannot be `enable`d (they're transient — they
    # are regenerated on every daemon-reload), but `WantedBy=default.target`
    # in the .container file makes them start automatically with the user
    # session, which linger keeps alive across reboots.
    systemctl_user "$VW_SYSTEM_USER" start vaultwarden.service
    success "Quadlet unit activated and started"

    # ── Step 9: Health check ──────────────────────────────────────────────────
    if ! wait_for_healthy "$hostname" "$port" "$ts_ip"; then
        warn "Check logs with: sudo -u $VW_SYSTEM_USER journalctl --user-unit vaultwarden -n 50"
    fi

    # ── Done ──────────────────────────────────────────────────────────────────
    section "Vaultwarden setup complete"
    echo ""
    info "https://$hostname"
    echo ""
    warn "Next steps:"
    warn "1. Visit https://$hostname and create your account"
    warn "2. Visit https://$hostname/admin to configure Vaultwarden"
    warn "   Admin token: sudo cat $token_reveal_file"
    warn "   Delete after use: sudo rm $token_reveal_file"
    warn "3. Once your account is set up, lock down the instance:"
    warn "   sudo $0 harden"
    echo ""
    info "Useful commands:"
    info "  Logs:          sudo -u $VW_SYSTEM_USER journalctl --user-unit vaultwarden -f"
    info "  Restart:       sudo -u $VW_SYSTEM_USER XDG_RUNTIME_DIR=/run/user/\$(id -u $VW_SYSTEM_USER) systemctl --user restart vaultwarden"
    info "  Status:        sudo -u $VW_SYSTEM_USER XDG_RUNTIME_DIR=/run/user/\$(id -u $VW_SYSTEM_USER) systemctl --user status vaultwarden"
    info "  Config:        $VW_ENV_FILE"
    info "  Data:          $VW_DATA_DIR"
    info "  Cert refresh:  $INSTALLED_SCRIPT cert-refresh $hostname  (cron: /etc/cron.d/vaultwarden-cert-refresh)"
    echo ""
    info "To update Vaultwarden in future:"
    info "  sudo $INSTALLED_SCRIPT update <version>   # e.g. update 1.35.5"
    echo ""
}

# ══════════════════════════════════════════════════════════════════════════════
# USAGE
# ══════════════════════════════════════════════════════════════════════════════
usage() {
    cat <<EOF
Vaultwarden Setup Script (Podman + Tailscale edition)

Sets up a Vaultwarden instance (self-hosted Bitwarden-compatible password
manager) running in a Podman container, with TLS provided directly by
Tailscale. No nginx or Let's Encrypt required — the droplet must already
be joined to a Tailscale network with MagicDNS and HTTPS certificates
enabled in the Tailscale admin console.

Usage:
  sudo ./setup_vaultwarden.sh <tailscale-hostname> [options]
  sudo ./setup_vaultwarden.sh harden
  sudo ./setup_vaultwarden.sh update [<version>|<image>] [--no-backup]
  sudo ./setup_vaultwarden.sh cert-refresh <tailscale-hostname>
  sudo ./setup_vaultwarden.sh --help

Arguments:
  <tailscale-hostname>   Full MagicDNS name of this machine, e.g.:
                           my-droplet.tail1234.ts.net

Subcommands:
  harden                 Disable signups and the admin interface after
                         initial account creation.
  update [<version>]     Roll the container forward to a new Vaultwarden
                         image. Backs up $VW_DATA_DIR, repins Image= in the
                         quadlet, restarts, health-checks, and rolls back to
                         the previous image if the new one doesn't come up.
                         Never touches $VW_ENV_FILE, so 'harden' settings and
                         the admin token survive. With no argument, updates
                         to the version pinned in this script ($VW_IMAGE).
                         Accepts a bare tag (1.35.5) or a full image
                         reference (docker.io/vaultwarden/server:1.35.5-alpine).
                         Tag-only targets are pinned to the digest pulled.
  cert-refresh <host>    Fetch/renew the Tailscale TLS certificate and
                         restart Vaultwarden if the cert changed. Run by
                         cron daily; safe to invoke manually.

Options (update only):
  --no-backup            Skip the pre-update tarball of $VW_DATA_DIR.

Options (setup only):
  --port <port>          Port to bind Vaultwarden on the Tailscale
                         interface (default: 443).
  --admin-token <token>  Token for the /admin interface
                         (default: randomly generated).
  --help, -h             Show this help and exit.

Examples:
  sudo ./setup_vaultwarden.sh my-droplet.tail1234.ts.net
  sudo ./setup_vaultwarden.sh my-droplet.tail1234.ts.net --port 8443
  sudo ./setup_vaultwarden.sh harden
  sudo ./setup_vaultwarden.sh update 1.35.5
  sudo ./setup_vaultwarden.sh cert-refresh my-droplet.tail1234.ts.net

Prerequisites:
  - Tailscale is installed, running, and this machine is joined to your tailnet.
  - MagicDNS is enabled in the Tailscale admin console (DNS → Enable MagicDNS).
  - HTTPS certificates are enabled (DNS → Enable HTTPS).
  - The 'vaultwarden' rootless-Podman service account already exists:
      sudo ./server/setup_rootless_podman.sh vaultwarden

What the setup subcommand does:
  1. Installs argon2
  2. Creates persistent data directory at /srv/vaultwarden
  3. Fetches a TLS certificate for the Tailscale hostname
  4. Installs a daily cert-refresh cron job
  5. Writes an env config file at /etc/vaultwarden/vaultwarden.conf
  6. Writes a Podman Quadlet (.container) unit for the vaultwarden user
  7. Pulls the Vaultwarden image
  8. Activates the Quadlet unit via systemctl --user

After setup:
  1. Visit https://<tailscale-hostname> and create your account.
  2. Visit https://<tailscale-hostname>/admin (admin token is in
     /root/vaultwarden-admin-token.txt — delete after use).
  3. Once your account is created, lock down the instance:
       sudo ./setup_vaultwarden.sh harden

Updating later:
  sudo $INSTALLED_SCRIPT update 1.35.5
  Re-running 'setup' is NOT an update path: it regenerates the admin token
  and re-enables signups.
EOF
}

# ══════════════════════════════════════════════════════════════════════════════
# ENTRYPOINT
# ══════════════════════════════════════════════════════════════════════════════
case "${1:-}" in
    harden) cmd_harden ;;
    update)
        shift
        cmd_update "$@"
        ;;
    cert-refresh) cmd_cert_refresh "${2:-}" ;;
    --help | -h) usage ;;
    "")
        usage >&2
        exit 1
        ;;
    *)
        cmd_setup "$@"
        ;;
esac
